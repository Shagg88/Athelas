"""Tiny assembler for Direct3D pixel shader 1.4 / 2.0 bytecode (the subset we use).

Usage: python3 psasm.py shader.asm NAME > out.h
Syntax (one instruction per line, ';' comments):
    ps_2_0
    dcl t0.xy
    dcl_2d s0
    texld r0, t0, s0
    mad r1.xy, r0.x, c0.x, c0.y
    mov oC0, r1
Registers: rN (temp), cN (const), tN (texcoord), sN (sampler), oC0.
Dest write masks (.x, .xy, .xyzw ...); source swizzles (.x, .xyzw, .wzyx ...),
source negate with a leading '-'.
"""
import sys, re

OPS = {  # name: (opcode, number of sources)
    'mov': (1, 1), 'add': (2, 2), 'sub': (3, 2), 'mad': (4, 3), 'mul': (5, 2),
    'rcp': (6, 1), 'rsq': (7, 1), 'dp3': (8, 2), 'dp4': (9, 2), 'min': (10, 2),
    'max': (11, 2), 'exp': (14, 1), 'log': (15, 1), 'lrp': (18, 3), 'frc': (19, 1),
    'pow': (32, 2), 'abs': (35, 1), 'nrm': (36, 1), 'cmp': (88, 3), 'dp2add': (90, 3),
    'texld': (66, 2), 'texcrd': (64, 1),
}
REGTYPE = {'r': 0, 'v': 1, 'c': 2, 't': 3, 's': 10, 'oC': 8}
COMP = {'x': 0, 'y': 1, 'z': 2, 'w': 3, 'r': 0, 'g': 1, 'b': 2, 'a': 3}


def regbits(name):
    m = re.fullmatch(r'(oC|[rvcts])(\d+)', name)
    if not m:
        raise SystemExit('bad register ' + name)
    t = REGTYPE[m.group(1)]
    n = int(m.group(2))
    return 0x80000000 | ((t & 7) << 28) | (((t >> 3) & 3) << 11) | n


def dest(tok):
    reg, _, mask = tok.partition('.')
    m = 0
    for ch in (mask or 'xyzw'):
        m |= 1 << COMP[ch]
    return regbits(reg) | (m << 16)


def src(tok):
    neg = tok.startswith('-')
    tok = tok.lstrip('-')
    reg, _, sw = tok.partition('.')
    sw = sw or 'xyzw'
    sw = (sw + sw[-1] * 4)[:4]
    s = 0
    for i, ch in enumerate(sw):
        s |= COMP[ch] << (2 * i)
    return regbits(reg) | (s << 16) | ((1 if neg else 0) << 24)


def assemble(text):
    out = []
    sm2 = True
    for line in text.splitlines():
        line = line.split(';')[0].strip()
        if not line:
            continue
        if line == 'ps_2_0':
            out.append(0xFFFF0200)
            continue
        if line == 'ps_1_4':                # no instruction-length field in 1.x
            out.append(0xFFFF0104)
            sm2 = False
            continue
        if line == 'phase':
            out.append(0x0000FFFD)
            continue
        op, _, rest = line.partition(' ')
        args = [a.strip() for a in rest.split(',')] if rest.strip() else []
        if op == 'dcl':                     # dcl tN.mask (texture coordinate input)
            out += [31 | (2 << 24), 0x80000000, dest(args[0])]
        elif op == 'dcl_2d':                # sampler declaration
            out += [31 | (2 << 24), 0x80000000 | (2 << 27), dest(args[0])]
        else:
            code, nsrc = OPS[op]
            if op == 'texld' and not sm2:
                nsrc = 1                    # ps_1_4: texld rN, tM/rM (stage = N)
            if len(args) != nsrc + 1:
                raise SystemExit('wrong operand count: ' + line)
            length = ((1 + nsrc) << 24) if sm2 else 0
            out += [code | length, dest(args[0])] + [src(a) for a in args[1:]]
    out.append(0x0000FFFF)
    return out


if __name__ == '__main__':
    words = assemble(open(sys.argv[1]).read())
    name = sys.argv[2]
    print('/* generated by scripts/psasm.py from %s */' % sys.argv[1])
    print('static const DWORD %s[] = {' % name)
    for i in range(0, len(words), 6):
        print('    ' + ', '.join('0x%08x' % w for w in words[i:i + 6]) + ',')
    print('};')
